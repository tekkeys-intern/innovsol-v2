/* ---------- job pages (built by scripts/jobs/build.cjs; only listed here for the sitemap) ---------- */
const jobs = fs.readdirSync(path.join(ROOT, 'public/careers')).filter((x) => x.endsWith('.html')).map((f) => `/careers/${f}`);

/* ---------- sitemap ---------- */
const today = new Date().toISOString().slice(0, 10);
const inds = fs.readdirSync(path.join(ROOT, 'public/industries')).filter((x) => x.endsWith('.html')).map((x) => `/industries/${x}`);
const urls = [['/', 1.0, 'weekly'], ['/careers', 0.8, 'weekly'], ...inds.map((u) => [u, 0.9, 'monthly']), ...jobs.map((u) => [u, 0.6, 'weekly']), ...((fs.existsSync(path.join(ROOT, 'scripts/.pages-manifest.json')) ? JSON.parse(read('scripts/.pages-manifest.json')) : []).map((m) => [m.path, m.priority, m.freq])), ['/privacy.html', 0.2, 'yearly'], ['/cookies.html', 0.2, 'yearly'], ['/terms.html', 0.2, 'yearly']];
write('public/sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.map(([u, pr, fr]) => `  <url><loc>${SITE}${u}</loc><lastmod>${today}</lastmod><changefreq>${fr}</changefreq><priority>${pr}</priority></url>`).join('\n')}\n</urlset>\n`);
